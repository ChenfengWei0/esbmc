#!/usr/bin/env python3
"""Generate the setFeeReceiver ladder: bare function -> real St1inch, one rung at a time.

WHY A LADDER AND NOT A LOOKALIKE. `D32` was a lookalike I built by hand, and it
SOLVED — which told me the chain was not the cause but not what was. A ladder
whose bottom is the real function verbatim and whose every rung adds exactly ONE
ingredient of the real contract cannot have that failure mode: the rung where the
behaviour changes IS the answer.

MEASURED BOTTOM (`step0_bare.sol`): the function alone, with only the owner, the
modifier, the error and the event, gives **4 paths, F 4, 100%, 0.002-0.004 s per
solve**. So the function is not the problem and the ladder is worth climbing.

MEASURED TOP (the real contract, D32): **5 paths, F 0** — `bounded-holds 2`,
`solver-unknown 3`, z3's own reason `out of memory`, ~10 s each, and 10 VCCs for
5 paths because the constructor calls this public unit (D33).

THE RUNGS, each adding one thing the real `St1inch` has:

  --ctor-calls-unit   the constructor calls setFeeReceiver. Real: St1inch.sol:108.
                      Known to double the claim count (D33) and to produce a RED
                      test (D34); known NOT to make anything unsolvable on its own.
  --exp-table         30 immutable `T_k = (T_{k-1}*T_{k-1})/1e18` in the
                      constructor. Real: VotingPowerCalculator. Known NOT to be
                      the cause on its own (D30, withdrawn by measurement).
  --vp-calls          the constructor CALLS a 30-branch `_votingPowerAt`, twice,
                      and compares the result. Real: St1inch.sol:106-107. This is
                      the ingredient D32 did NOT have -- a straight-line chain is
                      not the same as executing thirty branches each carrying a
                      256-bit multiply and divide, twice, inside the constructor.
  --erc20-strings     a `name`/`symbol` string pair assigned in the constructor.
                      Real: ERC20("Staking 1INCH v2", "st1INCH"). Every st1inch
                      log shows 59 `nondet_string`/`_str_assign` unwinding lines,
                      and the truncated-loop warning names exactly those.

Each switch is independent, so a rung can be tested alone or in combination, and
a 2^k cell can be run if the single-factor rungs all come back clean.

Usage: python3 gen_setfee_ladder.py <out.sol> [--ctor-calls-unit] [--exp-table]
                                    [--vp-calls] [--erc20-strings]
                                    [--depth N] [--width N] [--op muldiv|mul|div]
"""
import sys
from pathlib import Path

HEAD = """// SPDX-License-Identifier: MIT
pragma solidity 0.8.23;

/// GENERATED by notes/coverage/scripts/gen_setfee_ladder.py -- do not hand-edit.
/// rungs: {rungs}
///
/// The unit under measurement is `setFeeReceiver`, copied verbatim from
/// St1inch.sol, and it is IDENTICAL at every rung. Only the surrounding contract
/// changes, one ingredient at a time.
contract D36 {{
    error ZeroAddress();
    event FeeReceiverSet(address receiver);

    uint@W@ private constant _ONE_E18 = 1e18;
    uint@W@ private constant _VOTING_POWER_DIVIDER = 20;
    uint256 public constant MAX_LOCK_PERIOD = 2 * 365 days;

    address public owner;
    address public feeReceiver;
{decls}
    modifier onlyOwner() {{
        require(msg.sender == owner);
        _;
    }}

    constructor({ctor_args}) {{
        owner = msg.sender;
{ctor_body}    }}
{vp_fn}
    /// VERBATIM from St1inch.sol -- the unit under measurement.
    function setFeeReceiver(address feeReceiver_) public onlyOwner {{
        if (feeReceiver_ == address(0)) revert ZeroAddress();
        feeReceiver = feeReceiver_;
        emit FeeReceiverSet(feeReceiver_);
    }}
{table_reader}}}
"""

VP_FN = """
    /// The same shape as VotingPowerCalculator._votingPowerAt: THIRTY independent
    /// branches, each a 256-bit multiply and divide. Not a straight-line chain.
    function _votingPowerAt(uint@W@ balance, uint256 timestamp) internal view returns (uint@W@ votingPower) {{
        unchecked {{
            uint256 t = timestamp;
            votingPower = balance;
{branches}        }}
        return votingPower;
    }}
"""


def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    out = Path(argv[1])
    flags = set(a for a in argv[2:] if a.startswith("--"))
    depth = 30
    width = 256
    for i, a in enumerate(argv):
        if a == "--depth" and i + 1 < len(argv):
            depth = int(argv[i + 1])
        if a == "--width" and i + 1 < len(argv):
            width = int(argv[i + 1])

    ctor_calls = "--ctor-calls-unit" in flags
    exp_table = "--exp-table" in flags
    vp_calls = "--vp-calls" in flags
    strings = "--erc20-strings" in flags
    # `--vp-calls` needs the table to multiply by; asking for one without the
    # other would silently generate a different contract from the one named.
    if vp_calls and not exp_table:
        sys.exit("--vp-calls requires --exp-table: the branches multiply by the "
                 "table entries, and generating them without it would be a "
                 "different contract wearing the same rung name")

    decls, ctor_body, ctor_args = [], [], []
    if exp_table:
        decls += [f"    uint{width} public immutable T{i};\n" for i in range(depth)]
        ctor_args.append(f"uint{width} expBase_")
        ctor_body.append("        T0 = expBase_;\n")
        ctor_body += [f"        T{i} = (T{i-1} * T{i-1}) / _ONE_E18;\n"
                      for i in range(1, depth)]
    if strings:
        decls.append("    string public name;\n    string public symbol;\n")
        ctor_body.append('        name = "Staking 1INCH v2";\n'
                         '        symbol = "st1INCH";\n')
    if vp_calls:
        ctor_body.append(
            "        if (_votingPowerAt(1e18, block.timestamp + MAX_LOCK_PERIOD)"
            " * _VOTING_POWER_DIVIDER < 1e18) revert ZeroAddress();\n"
            "        if (_votingPowerAt(1e18, block.timestamp + MAX_LOCK_PERIOD"
            " + 1) * _VOTING_POWER_DIVIDER > 1e18) revert ZeroAddress();\n")
    if ctor_calls:
        ctor_args.append("address feeReceiver_")
        ctor_body.append("        setFeeReceiver(feeReceiver_);\n")

    # ---- WHICH OPERATOR? `--op mul` / `--op div` / default `muldiv` ----
    #
    # The branch-count sweep showed a CLIFF between 1 and 5 branches, a
    # NON-MONOTONE cost (depth 5 hits the 120 s per-claim timeout while depth 30
    # bails with `out of memory` in 17 s), and a formula that grows LINEARLY and
    # stays small throughout (123 -> 355 assignments, milliseconds to encode).
    # So the cost is not size. The remaining single factor inside the branch body
    # is which 256-bit operator it performs, and a bit-blasted 256-bit DIVISION
    # is a very different object from a multiplication.
    #
    # Kept as one generator with a switch so the three cells differ by exactly
    # the operator and nothing else.
    op = "muldiv"
    for i, a in enumerate(argv):
        if a == "--op" and i + 1 < len(argv):
            op = argv[i + 1]
    if op not in ("muldiv", "mul", "div"):
        sys.exit("--op must be muldiv, mul or div")
    body = {
        "muldiv": "votingPower = (votingPower * T{i}) / _ONE_E18;",
        "mul": "votingPower = votingPower * T{i};",
        "div": "votingPower = votingPower / _ONE_E18;",
    }[op]
    branches = ""
    if vp_calls:
        branches = "".join(
            f"            if (t & 0x{1 << i:x} != 0) {{ " + body.format(i=i)
            + " }\n" for i in range(depth))
    rungs_op = f" op={op}"

    rungs = (" ".join(sorted(flags)) or "(bare)") + (rungs_op if vp_calls else "")
    text = HEAD.format(
        rungs=rungs,
        decls="".join(decls) + ("\n" if decls else ""),
        ctor_args=", ".join(ctor_args),
        ctor_body="".join(ctor_body),
        vp_fn=(VP_FN.format(branches=branches) if vp_calls else ""),
        table_reader=("\n    function tableTop() public view returns (uint@W@) "
                      f"{{ return T{depth - 1}; }}\n" if exp_table else ""),
    )
    out.write_text(text.replace("uint@W@", f"uint{width}"))
    print(f"wrote {out}   rungs: {rungs} width={width}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

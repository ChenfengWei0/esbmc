#!/usr/bin/env python3
"""Does a 30-deep 256-bit mul/div CONSTRUCTOR chain make a 4-line setter unsolvable?

THE CLAIM UNDER TEST is D30's: st1inch's `setFeeReceiver` -- an owner check, a
zero check and one assignment -- reports 10 VCCs with 8 no-verdicts and z3's own
reason `out of memory`, and the cause is not its body but the inherited
constructor of `VotingPowerCalculator`, which builds thirty chained
`_EXP_TABLE_k = (prev * prev) / 1e18` over 256-bit words. ESBMC's harness runs
the constructor before every unit, so every path claim of every unit carries it.

That is an argument. This makes it a measurement, on a generated 20-line contract
whose ONLY variable is the chain depth.

PREDICTIONS, WRITTEN BEFORE THE RUN:

  * depth 3   -- the CONTROL. Every path of `setFeeReceiver` witnessed, sub-second
                 solves. If this does not happen the fixture measures NOTHING and
                 no depth above it may be read: "the setter is unsolvable" would
                 then be true of the setter rather than of the chain.
  * depth 30  -- reproduces st1inch's signature: F drops, `solver-unknown`
                 appears, solve times leave the sub-second band.
  * depth 15  -- placed between them on purpose. It says whether this is a CLIFF
                 or a gradient, and those imply different things: a gradient is a
                 cost curve anyone can plan around, a cliff is a capability
                 boundary.

  FALSIFIER, and it is the outcome that would sink D30: if depth 30 solves as
  cleanly as depth 3, the constructor chain is NOT what makes st1inch's claims
  undecidable, and the explanation has to be found somewhere else in that
  contract -- D30 would be withdrawn, not softened.

Every depth is generated by `gen_exp_chain_poc.py` so the cells cannot differ by
anything except the factor. Serial, `--memlimit 8g`, `start_new_session` +
`killpg` so a timeout leaves no orphan.

Usage: python3 exp_chain_sweep.py [--depths 3,15,30] [--timeout 180] [outdir]
"""
import argparse
import json
import os
import re
import signal
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
ESBMC = REPO / "build/src/esbmc/esbmc"
SOLC = "/usr/local/bin/solc"
GEN = HERE / "gen_exp_chain_poc.py"

RE_TIME = re.compile(r"Runtime decision procedure:\s*([0-9.]+)s")
RE_ASSIGN = re.compile(r"([0-9]+) assignments")


def cell(depth, wd, timeout, solver_flags=()):
    wd.mkdir(parents=True, exist_ok=True)
    sol = wd / f"D32_chain{depth}.sol"
    r = subprocess.run([sys.executable, str(GEN), str(depth), str(sol)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        return {"error": f"generator failed: {r.stdout}{r.stderr}"}
    ast = Path(str(sol) + ".solast")
    with ast.open("w") as fh:
        c = subprocess.run([SOLC, "--ast-compact-json", str(sol)], stdout=fh,
                           stderr=subprocess.PIPE, text=True)
    if c.returncode != 0:
        return {"error": f"solc failed: {c.stderr}"}

    cmd = [str(ESBMC), str(ast), "--sol", str(sol),
           "--solidity-path-coverage", "--contract", "D32",
           "--focus-function", "setFeeReceiver",
           "--solidity-max-tx", "1", "--cov-report-json",
           "--path-cov-max-goals", "10000", "--memlimit", "8g"] \
        + list(solver_flags)
    (wd / "cmd.txt").write_text(" ".join(cmd) + "\n")
    t0 = time.time()
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                         text=True, cwd=str(wd), start_new_session=True)
    try:
        out, rc = p.communicate(timeout=timeout)[0], p.returncode
    except subprocess.TimeoutExpired:
        os.killpg(os.getpgid(p.pid), signal.SIGKILL)
        out, rc = (p.communicate()[0] or ""), None
    (wd / "run.log").write_text(out or "")
    wall = round(time.time() - t0, 1)

    rep = wd / "cov-report.json"
    s = {}
    if rep.exists():
        try:
            s = json.loads(rep.read_text()).get("summary", {})
        except ValueError:
            s = {}
    times = [float(m.group(1)) for m in RE_TIME.finditer(out or "")]
    assigns = RE_ASSIGN.findall(out or "")
    return {
        "rc": rc, "wall": wall, "report": rep.exists(),
        "paths": s.get("paths_total"), "F": s.get("F_feasible_with_ce"),
        "U": s.get("U_undecided"),
        "reasons": {k: v for k, v in (s.get("U_reasons") or {}).items() if v},
        "times": times,
        "assignments": int(assigns[-1]) if assigns else None,
    }


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir", nargs="?", default="exp_chain_out")
    ap.add_argument("--depths", default="3,15,30")
    ap.add_argument("--timeout", type=int, default=180)
    # THE BACKEND MUST BE HELD FIXED, AND THE FIRST RUN OF THIS SCRIPT DID NOT.
    # With no flag ESBMC AUTO-SELECTS, and on this fixture it picks bitwuzla
    # ("Z3 is much slower on 256-bit bit-vector arithmetic") -- while the
    # st1inch run this was being compared against used `--z3
    # --tuple-node-flattener`. A falsification carried out on a different
    # backend from the phenomenon is confounded, whatever it shows.
    # `run_stats.py` prints the auto-selection line for exactly this reason.
    ap.add_argument("--solver-flags", default="",
                    help="space-separated backend flags, e.g. "
                         "'--z3 --tuple-node-flattener'. Pass the SAME ones the "
                         "phenomenon was observed under; leaving this empty lets "
                         "ESBMC auto-select and the comparison is then across "
                         "two backends as well as two depths")
    a = ap.parse_args(argv[1:])
    depths = [int(x) for x in a.depths.split(",")]
    sflags = a.solver_flags.split()
    for p in (ESBMC, Path(SOLC), GEN):
        if not Path(p).exists():
            sys.exit(f"missing {p}")

    print("## Does a deep 256-bit mul/div CONSTRUCTOR chain make a 4-line "
          "setter unsolvable?\n")
    print(f"binary : {ESBMC}  (mtime {int(ESBMC.stat().st_mtime)})")
    print(f"unit   : D32.setFeeReceiver -- identical at every depth")
    print(f"factor : constructor chain depth {depths}")
    print(f"backend: "
          + (" ".join(sflags) if sflags else
             "AUTO-SELECTED -- the backend is NOT held fixed, so this run "
             "compares two things at once")
          + "\n")

    res = {}
    for d in depths:
        r = cell(d, Path(a.outdir) / f"depth{d}", a.timeout, sflags)
        res[d] = r
        if "error" in r:
            print(f"    depth {d:<3} BUILD FAILED: {r['error']}")
            continue
        band = (f"{min(r['times']):.3f}-{max(r['times']):.3f}s over "
                f"{len(r['times'])}" if r["times"] else "no solve timed")
        print(f"    depth {d:<3} rc={str(r['rc']):<6} {r['wall']:>6}s  "
              f"assign={r['assignments']}  paths={r['paths']} F={r['F']} "
              f"U={r['U']}  {band}"
              + (f"  {r['reasons']}" if r["reasons"] else "")
              + ("" if r["report"] else "   NO REPORT"))

    print("\n" + "=" * 74)
    base = res.get(depths[0], {})
    if "error" in base or not base.get("report") or not base.get("paths"):
        print("  VOID -- the shallowest cell produced no measurement, so nothing "
              "above it can be\n  read. Fix the fixture first.")
        return 1
    if base.get("F") != base.get("paths"):
        print(f"  ⛔ VOID -- THE CONTROL DID NOT FIRE. At depth {depths[0]} only "
              f"{base.get('F')} of\n     {base.get('paths')} path(s) were "
              f"witnessed. 'The setter is unsolvable' would then be\n     true of "
              f"the SETTER, not of the chain, and no deeper cell is evidence "
              f"about\n     the chain at all.")
        return 1
    print(f"  ✅ control fired: depth {depths[0]} witnesses "
          f"{base['F']}/{base['paths']} path(s)\n")

    deep = [d for d in depths[1:] if res.get(d, {}).get("report")]
    degraded = [d for d in deep
                if (res[d].get("F") or 0) < (res[d].get("paths") or 0)]
    stalled = [d for d in depths[1:] if res.get(d, {}).get("rc") is None]

    if not degraded and not stalled:
        print("  ⛔ FALSIFIER FIRED: every depth witnesses every path. The "
              "constructor chain is NOT\n     what makes st1inch's claims "
              "undecidable, and D30 is WITHDRAWN rather than\n     softened -- "
              "the explanation has to be found elsewhere in that contract.")
        return 1
    if stalled:
        print(f"  depth(s) {stalled} did not return in {a.timeout}s -- "
              f"contributes nothing, NOT zero.")
    if degraded:
        print(f"  ✅ D30 REPRODUCED at depth(s) {degraded}: the SAME four-line "
              f"setter stops being\n     fully witnessed when only the "
              f"constructor chain grows. The cause is the\n     inherited "
              f"constructor, not the unit's body.")
    mid = [d for d in depths[1:-1] if res.get(d, {}).get("report")]
    if mid:
        print("\n  Shape between the ends (cliff vs gradient) -- read the F and "
              "solve-time\n  columns above; a gradient is a cost curve, a cliff "
              "is a capability boundary.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

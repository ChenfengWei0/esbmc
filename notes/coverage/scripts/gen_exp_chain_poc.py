#!/usr/bin/env python3
"""Generate the exp-table-chain PoC at a given depth. ONE factor: the depth.

WHY IT IS GENERATED AND NOT HAND-COPIED. The whole experiment is "same contract,
different chain length", and a 30-entry chain written out three times by hand is
three chances for the cells to differ by something other than the factor. The
generator guarantees that everything except the depth is byte-identical.

WHAT IT MODELS. `st1inch`'s `setFeeReceiver` is four lines:

    function setFeeReceiver(address feeReceiver_) public onlyOwner {
        if (feeReceiver_ == address(0)) revert ZeroAddress();
        feeReceiver = feeReceiver_;
        emit FeeReceiverSet(feeReceiver_);
    }

and D14 measured it at 1526 assignments, 10 VCCs, EIGHT of them with no verdict
and z3's own reason `out of memory`. Its own body cannot be that. D30 reads the
source and says the cause is inherited: `St1inch` extends
`VotingPowerCalculator`, whose CONSTRUCTOR builds thirty chained
`_EXP_TABLE_k = (prev * prev) / 1e18` over 256-bit words, and ESBMC's harness
runs the constructor before every unit -- so every path claim of every unit
carries the whole table's definition.

This file makes that testable at 20 lines instead of 4874: an owner-gated setter
whose body is the same shape, behind a constructor chain of DEPTH entries.

The generated contract deliberately keeps:
  * the `immutable` storage class (an immutable is fixed at construction, which
    is what puts the chain in the constructor rather than in a function);
  * `unchecked`-free arithmetic, matching the original;
  * one `revert` and one owner check, so the unit has real paths to enumerate
    and a witness means something.

Usage: python3 gen_exp_chain_poc.py <depth> <out.sol>
"""
import sys
from pathlib import Path

TEMPLATE_HEAD = """// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

/// GENERATED by notes/coverage/scripts/gen_exp_chain_poc.py -- do not hand-edit.
/// Chain depth: {depth}.  Everything else is identical across depths.
///
/// The question: st1inch's `setFeeReceiver` is an owner check, a zero check and
/// one assignment, and it reports 10 VCCs of which 8 get NO VERDICT with z3's
/// own reason `out of memory`. Its body cannot be why. D30 says the cause is the
/// inherited constructor -- thirty chained 256-bit `(prev * prev) / 1e18` -- which
/// ESBMC's harness runs before every unit, so every path claim carries it.
///
/// This isolates exactly that, with the chain depth as the only variable.
contract D32 {{
    error ZeroAddress();

    uint256 private constant _ONE_E18 = 1e18;

    address public owner;
    address public feeReceiver;

{decls}
    constructor(uint256 expBase_, address feeReceiver_) {{
        owner = msg.sender;
{body}{ctor_call}    }}

    /// The same shape as st1inch's, and the unit under measurement.
    function setFeeReceiver(address feeReceiver_) public {{
        require(msg.sender == owner);
        if (feeReceiver_ == address(0)) revert ZeroAddress();
        feeReceiver = feeReceiver_;
    }}

    /// A reader that USES the table, so the chain cannot be sliced away as dead.
    /// Without this the chain is written and never read, and the slicer would
    /// remove it -- which would make every cell identical and measure nothing.
    function tableTop() public view returns (uint256) {{
        return T{last};
    }}
}}
"""


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    depth = int(argv[1])
    if depth < 1:
        sys.exit("depth must be >= 1")
    out = Path(argv[2])
    # ---- THE SECOND FACTOR: does the CONSTRUCTOR call the unit? ----
    #
    # `St1inch.sol:108` does exactly that -- `setFeeReceiver(feeReceiver_)`
    # inside the constructor -- and `setFeeReceiver` is the only `public`
    # function of that contract the constructor calls. Every other setter is
    # `external`, which Solidity forbids calling internally.
    #
    # That is the difference the corpus shows: `setMaxLossRatio` (external) is
    # 5 paths / 5 VCCs, `setFeeReceiver` (public, called from the constructor) is
    # 5 paths / 10 VCCs, and it is the ONLY unit of st1inch with a ratio of 2 and
    # no external call. The unit's body then has TWO identities -- one execution
    # in constructor scope, one under the dispatcher -- and the instrumented
    # asserts run in both while sharing ONE claim key.
    ctor_call = "        setFeeReceiver(feeReceiver_);\n" \
        if "--ctor-calls-unit" in argv else ""

    decls = "".join(f"    uint256 public immutable T{i};\n" for i in range(depth))
    body = ["        T0 = expBase_;\n"]
    for i in range(1, depth):
        body.append(f"        T{i} = (T{i - 1} * T{i - 1}) / _ONE_E18;\n")

    out.write_text(TEMPLATE_HEAD.format(depth=depth, decls=decls,
                                        body="".join(body), last=depth - 1,
                                        ctor_call=ctor_call))
    print(f"wrote {out}  (chain depth {depth}"
          + (", CONSTRUCTOR CALLS THE UNIT" if ctor_call else "") + ")")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

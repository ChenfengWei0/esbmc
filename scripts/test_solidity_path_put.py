def make_case():
    fd, path = tempfile.mkstemp(suffix=".cov.t.sol")
    with os.fdopen(fd, "w") as f:
        f.write(EMITTED)
    try:
        em = EmittedFile(path)
    finally:
        os.unlink(path)
    case = em.case_for("sol:@C@FeeVault@F@setDiscount#61", 7)
    assert case is not None, "fixture: the emitted case for enc=7 was not found"
    return em, case


def check(cond, msg):
    if not cond:
        print(f"FAIL: {msg}")
        return 1
    print(f"ok: {msg}")
    return 0



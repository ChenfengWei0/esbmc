    bad += check("assertTrue(_put_ret," in text and "uint256(_put_ret)"
                 not in text,
                 "asserted directly, with no uint256 cast")
    bad += check(stats["return_asserts"] == 1,
                 f"one return assertion: {stats['return_asserts']}")
    return bad


